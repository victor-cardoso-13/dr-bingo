import { launch } from './cdp.mjs';
const p = await launch();
await p.goto('http://localhost:8081/');
const ok = (c, m) => console.log(c ? 'OK  ' : 'FAIL', m);
ok((await p.text('.topbar__value')) === 'USD 1.000,00', 'saldo USD 1.000,00');
await p.click('.btn-add'); await p.click('.btn-add');
ok((await p.text('.topbar__value')) === 'USD 21.000,00', 'adicionar x2 = USD 21.000,00');
await p.goto('http://localhost:8081/');
ok((await p.text('.topbar__value')) === 'USD 21.000,00', 'persistiu após reload');
await p.click('.card__head', 1);
ok((await p.text('.bet__total')) === 'Total: USD 3,00', 'desligar cartela 2 → Total 3');
for (const i of [0, 2, 3]) await p.click('.card__head', i).catch(() => {});
ok((await p.eval(`document.querySelectorAll('.card:not(.card--off)').length`)) === 1, 'sempre 1 ligada');
const before = await p.eval(`document.querySelector('.card__grid').textContent`);
await p.click('.btn-secondary', 1);
const after = await p.eval(`document.querySelector('.card__grid').textContent`);
ok(before !== after, 'trocar cartelas muda');
await p.goto('http://localhost:8081/');
ok(after === (await p.eval(`document.querySelector('.card__grid').textContent`)), 'cartelas persistem');
for (let i = 0; i < 12; i++) await p.click('.btn-step', 1).catch(() => {});
ok((await p.text('.bet__value')) === '1.000', 'aposta para no 1.000');
ok(await p.eval(`document.querySelectorAll('.btn-step')[1].disabled`), '+ desabilitado no 1.000');
// cartelas: 4 → 8 → 1
for (let i = 0; i < 6; i++) await p.click('.btn-step', 3).catch(() => {});
ok((await p.text('.bet__count')) === '8' && (await p.eval(`[...document.querySelectorAll('.card')].filter(c=>!c.hidden).length`)) === 8, '8 cartelas na tela');
ok((await p.text('.bet__total')) === 'Total: USD 5.000,00', '8 na tela, 5 ligadas (1 já estava + 4 novas): ' + await p.text('.bet__total'));
for (let i = 0; i < 9; i++) await p.click('.btn-step', 2).catch(() => {});
ok((await p.eval(`[...document.querySelectorAll('.card')].filter(c=>!c.hidden).length`)) === 1, '1 cartela na tela');
await p.goto('http://localhost:8081/');
ok((await p.text('.bet__count')) === '1', 'quantidade de cartelas persiste');
await p.setViewport(360, 740);
console.log('overflow', await p.eval(`[document.documentElement.scrollHeight, innerHeight, document.documentElement.scrollWidth]`));
console.log('errors', p.errors);
await p.close();
